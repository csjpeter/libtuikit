/* Generates src/width_table.c from glibc's wcwidth(3) in the C.UTF-8 locale. */

/*
 * Generates src/width_table.c: the code-point ranges whose display width is
 * not 1, taken from glibc's wcwidth(3) in the C.UTF-8 locale.
 *
 * Run by the "regen-width" target, at development time only; the output is
 * committed.  The source is glibc and not any terminal emulator, so the
 * renderer and the test instrument (libptytest) do not share a table: a
 * mistake in one is caught by the other.  The unit test test-text checks
 * that the committed table still matches the running glibc.
 *
 * Only widths 0 and 2 are recorded.  Code points glibc reports as -1
 * (unassigned, non-characters) are recorded as nothing, i.e. width 1: a
 * printable code point is never dropped (email-cli's rule).  Controls are
 * not taken from the table at all; tui_cp_width() handles them first.
 */

#define _XOPEN_SOURCE 700

#include <locale.h>
#include <stdio.h>
#include <stdlib.h>
#include <wchar.h>

static int table_width(unsigned cp) {
    if ((cp >= 0xD800 && cp <= 0xDFFF)) return 1;   /* never decoded */
    int w = wcwidth((wchar_t)cp);
    if (w == 0 || w == 2) return w;
    return 1;
}

int main(int argc, char **argv) {
    if (!setlocale(LC_CTYPE, "C.UTF-8")) {
        fprintf(stderr, "gen-width: the C.UTF-8 locale is not available\n");
        return 1;
    }
    FILE *out = stdout;
    if (argc > 1) {
        out = fopen(argv[1], "w");
        if (!out) {
            perror(argv[1]);
            return 1;
        }
    }
    fprintf(out,
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* Generated by tools/gen-width.c from glibc's C.UTF-8 wcwidth(3).\n"
        " * Do not edit; regenerate with: cmake --build <dir> --target regen-width */\n"
        "\n"
        "#include \"width_table.h\"\n"
        "\n"
        "const tui_width_range tui__width_ranges[] = {\n");
    unsigned count = 0;
    unsigned cp = 0xA0;    /* below this everything is a control or width 1 */
    while (cp <= 0x10FFFF) {
        int w = table_width(cp);
        if (w == 1) { cp++; continue; }
        unsigned lo = cp;
        while (cp + 1 <= 0x10FFFF && table_width(cp + 1) == w) cp++;
        fprintf(out, "    { 0x%05X, 0x%05X, %d },\n", lo, cp, w);
        count++;
        cp++;
    }
    fprintf(out, "};\n\nconst unsigned tui__width_range_count = %u;\n", count);
    if (out != stdout && fclose(out) != 0) {
        perror(argv[1]);
        return 1;
    }
    return 0;
}
